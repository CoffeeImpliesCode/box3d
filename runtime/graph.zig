//! The build half of Box3D's runtime route: three modules and one generated
//! file.
//!
//! An SDK that ships the runtime route calls `createModule` in place of
//! `translate.createModule()` and imports what comes back as its `c` module.
//! Nothing here links the native library. That is the point: in this
//! configuration the symbols arrive through the platform loader at run time,
//! and linking the archive as well would make the linker demand them before
//! `load` ever runs.
//!
//!   rt        runtime/loader.zig, the reusable core. Pure Zig; imported by the
//!             facade in both configurations, because `LoadSource` and
//!             `LoadError` are this SDK's public types and must be the same
//!             types whichever configuration is built.
//!   library   runtime/library.zig, this SDK's descriptor: the namespaced
//!             synchronization binding and the load-time checks.
//!   dispatch  generated by runtime/generate.zig from the real translation
//!             output: the table, the wrappers, `load`, and the re-exported
//!             translated namespace. It imports `rt`, `library` and the
//!             generator's patched translation as `c_native`, which imports the
//!             dispatch back as `c_routed`.
//!   sync.c    compiled into the dispatch with `-DRT_SYNC_PREFIX=box3d_rt`, so
//!             its symbols cannot collide with another SDK's.
//!
//! ## The one thing a caller must not do
//!
//! Do not link the compiled C archive into a module that imports this dispatch.
//! The facade's `c` import is the dispatch, and nothing else in the graph should
//! reference the library, or the linker resolves the symbols statically and the
//! runtime route silently becomes a linked one.

const std = @import("std");

/// The prefix `runtime/sync.c` is compiled with.
///
/// `runtime/library.zig` declares the same prefix in the symbol names it binds.
/// The two must agree, and a build where they do not fails to link, which is
/// the whole error report: there is no runtime path that could hide it.
///
/// A build that needs a second, independent instance of this SDK in one binary
/// should change this value *and* the prefix in `runtime/library.zig`, and then
/// give the second instance its own copy of both files. Nothing else in the
/// package assumes one instance.
const sync_prefix = "box3d_rt";

/// `extern` declarations that are really the C library's, and must stay direct.
///
/// Box3D's public headers reach exactly one C library header, and it reaches it
/// for two functions: `include/box3d/math_functions.h:10-11` includes `<math.h>`
/// "for sqrtf and remainderf". The other C library headers the public set
/// includes (`<stdbool.h>` and `<stdint.h>` at `base.h:6-7`, `<stddef.h>` at
/// `collision.h:11`, `<stdint.h>` at `types.h:11`, `<float.h>` at
/// `math_functions.h:8`) declare no function, so the entire C library surface
/// this translation can see is `<math.h>`. That was read out of the
/// translation rather than assumed: of the 1034 `extern` declarations this
/// build produced, 446 are not Box3D's and every one of them is a `<math.h>`
/// name (SOURCE-CONFIRMED, 2026-10-04, Debug, `x86_64-linux-gnu`).
///
/// The `<assert.h>` at `include/box3d/base.h:119` is never reached: line 115
/// takes the `__builtin_trap()` branch for every compiler this package
/// translates with, and `assert( 0 )` at line 120 is the branch that would
/// include it. `<assert.h>`'s `__assert_fail` is a C library name that no
/// header of this package reaches, so no name for it is claimed here.
///
/// ## Why this is spelled as bases and not as names
///
/// That surface is large, because glibc declares each `<math.h>` entry point
/// once per type it declares it for - `double`, `float` and `long double` from
/// `generic-glibc/math.h:445-536`, then again for each `_FloatN` and `_FloatNx`
/// type from `generic-glibc/math.h:561-678` - through `__MATHCALL` /
/// `__MATHDECL` (`bits/mathcalls-macros.h:29-45`), whose `__MATHDECL_1` emits
/// `extern <type> __MATH_PRECNAME(function,suffix) args __THROW`
/// (`bits/mathcalls-macros.h:38-39`). Writing the product out by hand is what
/// this file used to do, and a hand-written product is a transcription with a
/// missing entry waiting in it. The bases below plus the expansion are the
/// same answer without the transcription.
///
/// ## The classification helpers are not a `_GNU_SOURCE` question
///
/// The `isnan`, `isinf`, `finite`, `signbit`, `fpclassify`, `iseqsig` and
/// `issignaling` family is not declared by `bits/mathcalls.h` at all. It is
/// declared by `bits/mathcalls-helper-functions.h`, which every one of those
/// passes includes separately, and the `_FloatN` and `_FloatNx` passes include
/// it *outside* the `__GLIBC_USE (IEC_60559_TYPES_EXT)` guard that gates
/// `bits/mathcalls.h` - `generic-glibc/math.h:617-621` is the shape of it, and
/// the gate before that include is `__HAVE_DISTINCT_FLOAT128`, not a build
/// flag. So no build flag decides whether these names appear.
///
/// On `x86_64-linux-gnu` `__HAVE_DISTINCT_FLOAT128` is 1
/// (`x86-linux-gnu/bits/floatn.h:44-48`) and the `f16`, `f32`, `f64`, `f32x`,
/// `f64x` and `f128x` ones are 0: `generic-glibc/math.h:994-1001` refuses to
/// compile at all if any of those six is 1, and this build's translation
/// succeeded. That is why it produced `__isnanf128`, `__isinff128`,
/// `__finitef128`, `__fpclassifyf128`, `__iseqsigf128`, `__issignalingf128`
/// and `__signbitf128` and none of the other suffixes. Which one is 1 is a
/// property of the target, not of this build, and the expansion carries all
/// eight suffixes for every base because it cannot know which target it is
/// running for. `__MATHDECL_ALIAS` emits the plain name beside the
/// leading-underscore one, which is where `isnan`, `isinf`, `finite`,
/// `signbit`, `fpclassify`, `iseqsig` and `issignaling` themselves come from.
/// `signgam` is the one data symbol in this surface: `extern int signgam;` at
/// `generic-glibc/math.h:991`.
///
/// ## What the list this file replaces got wrong, and what it cost
///
/// It was the hand-written product of the three `double`/`float`/`long
/// double` passes alone, 663 names, and it was right about 419 of the 446
/// `<math.h>` names above. Its own comment explained the `_FloatN` gap as
/// "`_GNU_SOURCE` is not defined, so they stay out", which is a claim about
/// the wrong macro and is false for the header above (CORRECTED, 2026-10-04).
/// Twenty-seven names fell through it: the classification-helper family with
/// its `f128` suffix, its `__` spellings and its plain spellings, plus
/// `finitel`, `isnan`, `isnanf`, `isnanl`, `isinf`, `isinff`, `isinfl` and
/// `signgam`. `runtime/generate.zig` routed every one of them into the table,
/// which made a provider have to export `isnan`, so Box3D's own
/// `libbox3d.so` failed to load with `error.MissingSymbol`
/// (`local://foundation-resumed-box3d-loaded-static-Debug.json`,
/// 2026-10-04). Nothing else was affected: no `b3` name and no `box3dAbi_`
/// name is in the product below, so all 588 of them stay required.
///
/// ## Where the bases come from
///
/// `libc_math_bases` and `libc_extra_names` below are the lists
/// `../box2d/runtime/graph.zig` uses, taken unchanged, and that file records
/// where they came from: written by hand for glibc, then extended by
/// translating a `<math.h>`-including unit with the pinned compiler for every
/// platform in the published 53-platform matrix and reading out every name
/// that was neither Box2D's nor already spelled by the product. The same
/// measurement covers this SDK because the matrix is the same
/// (`cross-test.profile.sh` names no subset in either package) and the C
/// library surface is `<math.h>` alone, which is the paragraph above.
/// Box2D's file records nine NetBSD platforms and `powerpc64le-openbsd` as
/// translations that failed inside `translate-c` and names nothing for them.
/// This file inherits that gap rather than closing it: the product is a
/// superset, so a name only those targets declare is a name that would be
/// routed and asked of the provider, which would then be refused with
/// `error.MissingSymbol`.
///
/// The product is disjoint from everything Box3D owns, and that is a property
/// of the spelling rather than of this file: every Box3D entry point begins
/// `b3`, and the ten `box3dAbi_` ones begin `box3dAbi_`, while every name the
/// product can spell is a prefix of `""` or `"__"` followed by a base, and no
/// base, prefix, suffix or extra begins `b3`. The 3160 names of the product
/// were checked against all 588 `b3`/`box3dAbi_` names this build's
/// translation and both of its cached Debug dispatches carry, and the
/// intersection is empty (SOURCE-CONFIRMED, 2026-10-04).
///
/// A name absent from this product is routed: it goes into the table and the
/// provider is required to export it. So the product is deliberately a
/// superset of what any one target's `<math.h>` declares. Listing a name that
/// never appears costs nothing, because the generator consults the list per
/// declaration the translation actually produced; omitting one that does is
/// what turns a provider that is this package's own library into
/// `error.MissingSymbol`, which `runtime/loader.zig:480-494` returns after
/// printing the name of the first required symbol it could not resolve — so a
/// provider that is short of one `<math.h>` name is reported by that name and
/// not as a bare error.
const libc_math_bases =
    \\acos,acosh,asin,asinh,atan,atan2,atanh,
    \\cbrt,copysign,cos,cosh,sin,sinh,tan,tanh,
    \\exp,exp2,expm1,log,log10,log1p,log2,logb,
    \\fabs,fdim,fmax,fmin,fmod,fma,frexp,ldexp,modf,pow,sqrt,remainder,remquo,
    \\hypot,erf,erfc,lgamma,tgamma,
    \\ceil,floor,trunc,rint,round,nearbyint,roundeven,
    \\drem,significand,nan,j0,j1,jn,y0,y1,yn,gamma,lgamma_r,
    \\nextafter,nexttoward,scalbn,ilogb,scalbln,lrint,llrint,lround,llround,scalb,
    \\getpayload,getsign,putpayload,
    \\fegetround,fesetround,fegetenv,fesetenv,feholdexcept,fetestexcept,
    \\feraiseexcept,feupdateenv,fegetmode,fesetmode,
    \\_copysign,_finite,_hypot,_j0,_j1,_jn,_y0,_y1,_yn,
    \\finite,isnan,isinf,isfinite,isnormal,issignaling,signbit,fpclassify,iseqsig,
    \\chgsign,fpclass,signgam,sincos,cospi,sinpi,tanpi,exp10,inf,infinity,
    \\abs,atof,labs,gamma_r,rinttol,roundtol,
    \\__inline_isfinite,__inline_isinf,__inline_isnormal,
    \\_chgsign,_isnan,_logb,_nextafter,_fpclass,_cabs,_scalb,_matherr
;

/// `<math.h>` names on these targets that no prefix and precision suffix
/// spells, appended to the product verbatim.
///
/// Three shapes are here and none of them is a base: names with no precision
/// suffix to vary (`__math_errhandling`, the `__mingw_*` helpers, the Darwin
/// `__sincos*_stret` entry points and the `__imp__` import alias); names ending
/// in `d`, which is a helper suffix rather than one of the precision suffixes
/// above (`__fpclassifyd`, `__inline_isfinited`, `__inline_isinfd`); and
/// `_atof_l`, whose underscore is part of the name and not a suffix.
const libc_extra_names =
    \\__fpclassifyd,__imp__HUGE,__inline_isfinited,__inline_isinfd,__math_errhandling,
    \\__mingw_get_crt_info,__mingw_raise_matherr,__mingw_setusermatherr,__prefetch,
    \\__setusermatherr,__sincos_stret,__sincosf_stret,__sincospi_stret,__sincospif_stret,_atof_l
;

/// Scratch for `libc_noise`, which is computed rather than written out.
///
/// The size is a ceiling, not a figure of merit: it is what the expansion needs
/// with room to spare, and a comptime write past it is a build error rather
/// than a silently truncated symbol list. The bases and extras above spell 3160
/// names occupying 35586 bytes of it, separators included, so 64 KiB leaves
/// about 30000 bytes of room and a base added later cannot quietly overflow
/// it.
///
/// The buffer is a field of a `const` rather than a container-level `var` for
/// the reason the expansion has to run at comptime at all: only a `const`'s
/// initializer is comptime, and a container-level `var` is run-time storage no
/// matter which one wrote to it. `libc_noise_storage` below is filled by a
/// block expression and is immutable afterwards, so the generator is handed
/// the same bytes every run.
const Noise = struct {
    buf: [64 * 1024]u8,
    len: usize,
};

/// Reserves the next `len` bytes, comma-separated from the name before.
///
/// A non-empty buffer means a name has already been written, and no name here
/// is empty, so that comma is the separator. Every write below goes through
/// here, so the separator rule and the buffer bound live in one place; a name
/// that does not fit is a comptime slice panic, which is the build error this
/// file wants rather than a silently truncated symbol list.
fn reserve(storage: *Noise, len: usize) []u8 {
    if (storage.len != 0) {
        storage.buf[storage.len] = ',';
        storage.len += 1;
    }
    const at = storage.len;
    storage.len += len;
    return storage.buf[at..][0..len];
}

/// The expanded names, in comptime-owned storage.
const libc_noise_storage: Noise = blk: {
    @setEvalBranchQuota(100_000);
    // The element type is spelled out rather than left to inference. `.{"",
    // "__"}` is a tuple whose fields peer-resolve against each other, so the
    // capture in the `for` below is whatever that resolution produced rather
    // than a slice; on Zig 0.16.0 that capture is `[0:0]u8`, which has no
    // `.len` field, and a consumer build of this SDK reports exactly that at
    // the `prefix.len` below. `[_][]const u8` leaves the capture a
    // `[]const u8` and leaves nothing to resolve.
    const prefixes = [_][]const u8{ "", "__" };
    const suffixes = [_][]const u8{
        "",     "f",      "l",      "f16",   "f32",   "f64",
        "f128", "f16x",   "f32x",   "f64x",  "f128x", "ieee128",
    };
    var storage: Noise = .{ .buf = undefined, .len = 0 };
    var bases = std.mem.splitScalar(u8, libc_math_bases, ',');
    while (bases.next()) |part| {
        // The bases are written wrapped across lines, so each part carries the
        // newline and indentation that wrapped it. Trimming here is what makes
        // a wrapped list mean what it looks like.
        const base = std.mem.trim(u8, part, " \t\r\n");
        if (base.len == 0) continue;
        const reentrant = std.mem.endsWith(u8, base, "_r");
        const stem: []const u8 = if (reentrant) base[0 .. base.len - 2] else base;
        // The precision suffix goes between the stem and the `_r` reentrant
        // marker, which is why `gamma_r` also spells `gammaf_r` and `gammal_r`.
        const marker: []const u8 = if (reentrant) "_r" else "";
        for (prefixes) |prefix| {
            for (suffixes) |suffix| {
                const name = reserve(&storage, prefix.len + stem.len + suffix.len + marker.len);
                @memcpy(name[0..prefix.len], prefix);
                @memcpy(name[prefix.len..][0..stem.len], stem);
                @memcpy(name[prefix.len + stem.len ..][0..suffix.len], suffix);
                @memcpy(name[prefix.len + stem.len + suffix.len ..][0..marker.len], marker);
            }
        }
    }
    var extras = std.mem.splitScalar(u8, libc_extra_names, ',');
    while (extras.next()) |part| {
        const name = std.mem.trim(u8, part, " \t\r\n");
        if (name.len == 0) continue;
        @memcpy(reserve(&storage, name.len), name);
    }
    break :blk storage;
};

/// Every name the bases and the extras can appear as, comma separated.
///
/// Built at comptime from `libc_math_bases` and `libc_extra_names` so the
/// source keeps the readable form and the argument keeps the complete form.
/// This is a slice of the immutable storage above rather than a mutable
/// buffer.
const libc_noise: []const u8 = libc_noise_storage.buf[0..libc_noise_storage.len];

/// `extern` declarations the provider may legitimately not export.
///
/// Box3D's public headers declare one entry point that is absent from some
/// builds, and it is not optional here either: `b3InternalAssert` is declared
/// under `#if !defined( NDEBUG ) || defined( B3_ENABLE_ASSERT )`
/// (`include/box3d/base.h:123-131`) and defined under the same guard
/// (`src/core.c:81-90`). Both halves of a build see the same `-Doptimize`, so
/// the translation declares it in Debug and ReleaseSafe and does not declare it
/// in ReleaseFast and ReleaseSmall, and the object exports it in exactly the
/// same two modes. A declaration that is not in the translation is not in the
/// table, so there is nothing here to make optional; the list is spelled out so
/// that adding a genuinely conditional entry point is a build-file change with
/// a name in it.
const provider_optional = "";

/// `extern` declarations this build does not require a provider to export.
///
/// None. Every function the selected headers declare is expected from a
/// provider, and a provider that does not export one of them is refused rather
/// than half used.
///
/// A name here is routed and optional rather than direct; only
/// `libc_noise` above stays direct.
const provider_excluded = "";

/// The loader core, for a *linked* build to import.
///
/// A linked build has no dispatch, so the facade needs the core module itself
/// for the two public types `LoadSource` and `LoadError`: they are this SDK's
/// types and they must be the same types a caller names in either configuration.
/// It costs a linked build two declarations and no code, since nothing else in
/// that module is referenced until a configuration actually instantiates the
/// loader.
///
/// A runtime-loading build must *not* import this separately: `createModule`
/// makes the one core instance the dispatch uses, and the dispatch re-exports
/// the two types from it. Two instances would be two sets of types, and a
/// consumer would be naming one while `load` expects the other.
pub fn createCoreModule(
    b: *std.Build,
    target: std.Build.ResolvedTarget,
    optimize: std.builtin.OptimizeMode,
) *std.Build.Module {
    return b.createModule(.{
        .root_source_file = b.path("runtime/loader.zig"),
        .target = target,
        .optimize = optimize,
        // The Unix backend calls `dlopen`, which is libc. Nothing in this module
        // is compiled into a linked build, so this costs nothing there.
        .link_libc = true,
    });
}

/// The runtime-loaded `c` module for one target.
///
/// `translate` is the translation step for that same target and configuration;
/// its output is read by the generator, so the dispatch describes the header
/// this build actually selected rather than another one.
pub fn createModule(
    b: *std.Build,
    translate: *std.Build.Step.TranslateC,
    target: std.Build.ResolvedTarget,
    optimize: std.builtin.OptimizeMode,
) *std.Build.Module {
    const core = createCoreModule(b, target, optimize);

    const library = b.createModule(.{
        .root_source_file = b.path("runtime/library.zig"),
        .target = target,
        .optimize = optimize,
    });
    library.addImport("rt", core);

    return createDispatchModule(b, translate, target, optimize, core, library);
}

const GeneratedSources = struct {
    native: std.Build.LazyPath,
    dispatch: std.Build.LazyPath,
};

fn createDispatchModule(
    b: *std.Build,
    translate: *std.Build.Step.TranslateC,
    target: std.Build.ResolvedTarget,
    optimize: std.builtin.OptimizeMode,
    core: *std.Build.Module,
    library: *std.Build.Module,
) *std.Build.Module {
    const sources = generateDispatch(b, translate, target);

    const dispatch = b.createModule(.{
        .root_source_file = sources.dispatch,
        .target = target,
        .optimize = optimize,
        .link_libc = true,
    });
    dispatch.addImport("rt", core);
    dispatch.addImport("library", library);
    // The translated header, under a name that says what it is. Every type and
    // constant in the dispatch is re-exported from here rather than restated, so
    // `c.b3BodyDef` in a facade and `c_native.b3BodyDef` in the dispatch are
    // one type.
    //
    // The root is the generator's *patched* translation, not the raw one the
    // translate step wrote. `const __root = @import("c_routed");` is what makes
    // a macro-expanded struct member that names a library function resolve to
    // the routed wrapper rather than escaping to a native `extern` this route
    // never links. That repointing is why the two modules import each other.
    const native = b.createModule(.{
        .root_source_file = sources.native,
        .target = target,
        .optimize = optimize,
        .link_libc = true,
    });
    native.addImport("c_routed", dispatch);
    dispatch.addImport("c_native", native);
    dispatch.addCSourceFiles(.{
        .files = &.{"runtime/sync.c"},
        .flags = &.{b.fmt("-DRT_SYNC_PREFIX={s}", .{sync_prefix})},
        .language = .c,
    });
    return dispatch;
}

/// Runs the generator over the translation step's real output.
///
/// The generator is a host program built and run by this build, so the dispatch
/// is produced for the target being built from that target's own translation.
/// Nothing is cached across configurations: a different header configuration
/// produces a different translation step output, which produces a different
/// dispatch.
fn generateDispatch(
    b: *std.Build,
    translate: *std.Build.Step.TranslateC,
    target: std.Build.ResolvedTarget,
) GeneratedSources {
    const generator = b.addExecutable(.{
        .name = b.fmt("box3d-runtime-generate-{s}", .{
            target.result.zigTriple(b.allocator) catch @panic("unspellable target"),
        }),
        .root_module = b.createModule(.{
            .root_source_file = b.path("runtime/generate.zig"),
            .target = b.graph.host,
            .optimize = .Debug,
        }),
    });

    const run = b.addRunArtifact(generator);
    run.addArg("--library");
    run.addArg("box3d");
    run.addArg("--translate");
    run.addFileArg(translate.getOutput());
    if (libc_noise.len != 0) {
        run.addArg("--noise");
        run.addArg(libc_noise);
    }
    if (provider_optional.len != 0) {
        run.addArg("--optional");
        run.addArg(provider_optional);
    }
    if (provider_excluded.len != 0) {
        run.addArg("--exclude");
        run.addArg(provider_excluded);
    }
    run.addArg("--native-output");
    const native_source = run.addOutputFileArg("native.zig");
    run.addArg("--output");
    const dispatch_source = run.addOutputFileArg("dispatch.zig");
    return .{ .native = native_source, .dispatch = dispatch_source };
}